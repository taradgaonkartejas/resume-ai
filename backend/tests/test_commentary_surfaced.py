"""The ScoringAgent's prose must reach a screen, and must admit when it is old.

For most of this project the commentary layer was WRITE-ONLY: generated by a
model call on every analysis, persisted, and read by nobody. `AnalysisOut`
fixed half of that by returning it; no component ever rendered it, and the
guided editor -- the one screen where per-category advice is useful -- did
not even receive it.

The second half of the problem is that this prose is a SNAPSHOT while the
findings beside it are recomputed live on every request. Edit a bullet and
the two disagree, with the prose looking the more authoritative of the pair.
So it travels with a staleness flag.
"""

from __future__ import annotations

import uuid as _uuid

from app.services.heuristics import data_fingerprint
from tests.conftest import new_resume

SAMPLE = {
    "contact": {"name": "Sam Rivera", "headline": "Engineer", "email": "s@x.io",
                "phone": "", "location": "", "links": []},
    "summary": {"text": "Engineer with six years building platforms."},
    "experience": [{
        "company": "Acme", "role": "Engineer", "dates": "",
        "bullets": ["Cut build times from 20 minutes to 6 minutes."],
    }],
    "projects": [], "education": [],
    "skills": [{"label": "Languages", "items": ["Python", "SQL"]}],
}


def _steps(client, user_id, resume_id):
    r = client.get(f"/api/resumes/{resume_id}/analysis/steps",
                   headers={"X-User-Id": user_id})
    assert r.status_code == 200, r.text
    return r.json()


def test_steps_carry_commentary_fields(client, priya, priya_resume):
    body = _steps(client, priya, priya_resume)
    assert "commentary" in body
    assert "headline" in body["commentary"]
    assert "category_notes" in body["commentary"]
    assert "commentary_stale" in body


def test_no_analysis_yet_is_empty_and_NOT_marked_stale(client, priya, priya_resume):
    """Nothing to show is not the same as something out of date.

    Flagging an absent commentary as stale would put a "from your last
    analysis" note on a resume that has never been analysed.
    """
    body = _steps(client, priya, priya_resume)
    assert body["commentary"]["headline"] == ""
    assert body["commentary_stale"] is False


def test_fresh_commentary_is_not_stale(client, priya):
    from app.models import AnalysisReport, Resume

    db_session = client._session_factory()

    resume_id = new_resume(client, priya, "Fresh", dict(SAMPLE))
    resume = db_session.get(Resume, _uuid.UUID(str(resume_id)))
    data = resume.structured_data or {}

    db_session.add(AnalysisReport(
        resume_id=resume.id, overall_score=70, category_scores={}, role_tags=[],
        trace={
            "commentary": {"headline": "Solid.", "category_notes": {"summary": "ok"}},
            "data_fingerprint": data_fingerprint(data),
        },
    ))
    db_session.commit()

    body = _steps(client, priya, str(resume_id))
    assert body["commentary"]["headline"] == "Solid."
    assert body["commentary_stale"] is False


def test_editing_the_resume_marks_the_prose_stale(client, priya):
    """The whole point. Prose about a summary the user has since rewritten
    must not be presented as current."""
    from app.models import AnalysisReport, Resume

    db_session = client._session_factory()

    resume_id = new_resume(client, priya, "Drifts", dict(SAMPLE))
    resume = db_session.get(Resume, _uuid.UUID(str(resume_id)))
    db_session.add(AnalysisReport(
        resume_id=resume.id, overall_score=70, category_scores={}, role_tags=[],
        trace={
            "commentary": {"headline": "Written about the OLD text.",
                           "category_notes": {"summary": "leans on filler"}},
            "data_fingerprint": data_fingerprint(resume.structured_data or {}),
        },
    ))
    db_session.commit()
    assert _steps(client, priya, str(resume_id))["commentary_stale"] is False

    data = dict(resume.structured_data or {})
    data["summary"] = {"text": "A completely different summary now."}
    resume.structured_data = data
    db_session.commit()

    body = _steps(client, priya, str(resume_id))
    assert body["commentary_stale"] is True, (
        "the resume changed under the prose and the UI was not told"
    )
    # Still returned: the user keeps the insight, with its age attached.
    assert body["commentary"]["headline"] == "Written about the OLD text."


def test_a_report_with_no_fingerprint_is_assumed_stale(client, priya):
    """Reports written before fingerprints existed cannot prove freshness.

    Stale is the safe direction: an unnecessary note costs nothing, while
    presenting old prose as current is the failure being prevented.
    """
    from app.models import AnalysisReport, Resume

    db_session = client._session_factory()

    resume_id = new_resume(client, priya, "Legacy", dict(SAMPLE))
    resume = db_session.get(Resume, _uuid.UUID(str(resume_id)))
    db_session.add(AnalysisReport(
        resume_id=resume.id, overall_score=70, category_scores={}, role_tags=[],
        trace={"commentary": {"headline": "Old report.", "category_notes": {}}},
    ))
    db_session.commit()

    body = _steps(client, priya, str(resume_id))
    assert body["commentary_stale"] is True
